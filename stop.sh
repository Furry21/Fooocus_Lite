#!/bin/bash

echo "[Avery Core] Начинаю экстренное торможение нейросети..."

# Ищем процесс, который занял наш порт 8000, и безжалостно его убиваем
PID=$(lsof -t -i:8000)

if [ -z "$PID" ]; then
    echo "[Memory] Процесс на порту 8000 не найден. Нейросеть уже спит!"
else
    kill -9 $PID
    echo "[Memory] Сервер FastAPI успешно остановлен. Видеокарта полностью свободна!"
fi

# На всякий случай зачищаем зависшие процессы uvicorn/python проекта
pkill -f "uvicorn main:app"

sleep 2



